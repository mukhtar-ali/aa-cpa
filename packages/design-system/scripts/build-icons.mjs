#!/usr/bin/env node
/**
 * @file build-icons.mjs  (task T034)
 * Generates typed React icon components from `assets/icons/*.svg` into `src/icons/generated/`.
 *
 * - One component per SVG (`PascalCase` of the file name + `Icon`), plus `index.ts` with the `IconName` union, a registry and
 *   per-icon metadata (native size, directional flag).
 * - Colours: Figma exports use fixed hex values. They are mapped here so components contain no literals:
 *   `#9ddbf4` -> var(--color-icon-accent), `#132015` -> var(--color-bg-inverse), everything else -> currentColor.
 * - Icons keep their native viewBox and render at that size by default (so stroke widths match the design).
 * - Clip paths that only clip to the viewBox rectangle are removed (they carry colliding ids and do nothing).
 * - Directional icons (mirrored in RTL) are listed in `DIRECTIONAL` below.
 *
 *   node scripts/build-icons.mjs [--input DIR] [--out-dir DIR]
 */
import fs from 'node:fs';
import path from 'node:path';
import process from 'node:process';
import { fileURLToPath } from 'node:url';

/** File names (without .svg) of icons that must mirror in RTL. Extend when arrow/chevron icons are added. */
export const DIRECTIONAL = new Set(['arrow', 'arrow-start', 'arrow-end', 'chevron', 'chevron-start', 'chevron-end']);

const COLOUR_MAP = new Map([
  ['#9ddbf4', 'var(--color-icon-accent)'],
  ['#132015', 'var(--color-bg-inverse)'],
]);

const ATTR_RENAME = new Map([['class', 'className']]);
const DROP_ATTRS = new Set(['id', 'xmlns', 'style', 'overflow', 'preserveAspectRatio', 'width', 'height', 'viewBox', 'fill-opacity', 'stroke-opacity']);

export function toPascalCase(name) {
  return name
    .split(/[^a-zA-Z0-9]+/)
    .filter(Boolean)
    .map((p) => p[0].toUpperCase() + p.slice(1))
    .join('');
}

const camel = (attr) => ATTR_RENAME.get(attr) ?? attr.replace(/-([a-z])/g, (_, c) => c.toUpperCase());

function mapColour(value) {
  const v = value.trim().toLowerCase();
  if (v === 'none' || v.startsWith('url(') || v === 'currentcolor') return value;
  return COLOUR_MAP.get(v) ?? 'currentColor';
}

/** Parse the root element and return { viewBox, size, inner }. */
export function parseSvg(source, file = 'icon') {
  const root = source.match(/<svg\b([^>]*)>([\s\S]*)<\/svg>\s*$/);
  if (!root) throw new Error(`${file}: not a valid <svg> document`);
  const vb = root[1].match(/viewBox="([^"]+)"/);
  if (!vb) throw new Error(`${file}: missing viewBox`);
  const [minX, minY, w, h] = vb[1].split(/[\s,]+/).map(Number);
  if ([minX, minY, w, h].some(Number.isNaN)) throw new Error(`${file}: invalid viewBox "${vb[1]}"`);
  let inner = root[2];

  // Drop clip paths that only clip to the viewBox rectangle; fail on any other clip/mask/filter we cannot convert safely.
  const clipIds = [...inner.matchAll(/<clipPath id="([^"]+)">([\s\S]*?)<\/clipPath>/g)];
  for (const [whole, id, body] of clipIds) {
    const rect = body.match(/d="M0 0h([\d.]+)v([\d.]+)H0z"/) || body.match(/<rect[^>]*width="([\d.]+)"[^>]*height="([\d.]+)"/);
    if (!rect || Number(rect[1]) !== w || Number(rect[2]) !== h) throw new Error(`${file}: clipPath ${id} is not the viewBox rectangle`);
    inner = inner.replace(whole, '').replace(new RegExp(`\\s+clip-path="url\\(#${id}\\)"`, 'g'), '');
  }
  inner = inner.replace(/<defs>\s*<\/defs>/g, '');
  if (/<(mask|filter|style|script|image|foreignObject|use)\b/.test(inner)) throw new Error(`${file}: unsupported element`);
  return { viewBox: vb[1], width: w, height: h, inner: inner.trim() };
}

/** Convert the inner SVG markup to JSX. */
export function toJsx(inner) {
  return inner.replace(/<(\/?)([a-zA-Z]+)([^>]*?)(\/?)>/g, (_m, close, tag, attrs, selfClose) => {
    if (close) return `</${tag}>`;
    const out = [];
    for (const [, name, value] of attrs.matchAll(/([a-zA-Z:-]+)="([^"]*)"/g)) {
      if (DROP_ATTRS.has(name)) continue;
      if (name === 'fill' || name === 'stroke' || name === 'stop-color') out.push(`${camel(name)}="${mapColour(value)}"`);
      else out.push(`${camel(name)}="${value}"`);
    }
    return `<${tag}${out.length ? ' ' + out.join(' ') : ''}${selfClose ? ' /' : ''}>`;
  });
}

export function componentSource(name, parsed) {
  const component = `${toPascalCase(name)}Icon`;
  const jsx = toJsx(parsed.inner);
  return `/* Generated by scripts/build-icons.mjs from assets/icons/${name}.svg - DO NOT EDIT */
import * as React from 'react';
import type { IconComponentProps } from '../types';

export const ${component} = React.forwardRef<SVGSVGElement, IconComponentProps>(({ title, ...props }, ref) => (
  <svg ref={ref} viewBox="${parsed.viewBox}" fill="none" xmlns="http://www.w3.org/2000/svg" {...props}>
    {title ? <title>{title}</title> : null}
    ${jsx}
  </svg>
));
${component}.displayName = '${component}';
`;
}

export function buildIcons(options = {}) {
  const here = path.dirname(fileURLToPath(import.meta.url));
  const pkg = path.resolve(here, '..');
  const inputDir = path.resolve(process.cwd(), options.inputDir ?? path.join(pkg, 'assets/icons'));
  const outDir = path.resolve(process.cwd(), options.outDir ?? path.join(pkg, 'src/icons/generated'));
  if (!fs.existsSync(inputDir)) throw new Error(`Icon directory not found: ${inputDir}`);
  // The output directory is deleted and recreated: never allow the filesystem root, the working directory, the package or any parent of them
  // (for example `--out-dir .` or `--out-dir ..`).
  const protectedDirs = [process.cwd(), pkg].map((dir) => path.resolve(dir));
  if (outDir === path.parse(outDir).root || protectedDirs.some((dir) => dir === outDir || dir.startsWith(outDir + path.sep))) {
    throw new Error(`Refusing to use ${outDir} as the output directory: it would be deleted and it contains the working directory or the package.`);
  }

  const files = fs.readdirSync(inputDir).filter((f) => f.endsWith('.svg')).sort();
  if (files.length === 0) throw new Error(`No .svg files in ${inputDir}`);

  fs.rmSync(outDir, { recursive: true, force: true });
  fs.mkdirSync(outDir, { recursive: true });

  const seen = new Set();
  const entries = [];
  for (const file of files) {
    const name = file.replace(/\.svg$/, '');
    if (!/^[a-z0-9]+(-[a-z0-9]+)*$/.test(name)) throw new Error(`Icon file name must be kebab-case: ${file}`);
    const component = `${toPascalCase(name)}Icon`;
    if (seen.has(component)) throw new Error(`Duplicate icon component ${component}`);
    seen.add(component);
    const parsed = parseSvg(fs.readFileSync(path.join(inputDir, file), 'utf8'), file);
    fs.writeFileSync(path.join(outDir, `${component}.tsx`), componentSource(name, parsed));
    entries.push({ name, component, size: Math.max(parsed.width, parsed.height), directional: DIRECTIONAL.has(name) });
  }

  const index = [
    '/* Generated by scripts/build-icons.mjs - DO NOT EDIT */',
    "import type { IconComponent } from '../types';",
    ...entries.map((e) => `import { ${e.component} } from './${e.component}';`),
    '',
    `export const iconNames = [${entries.map((e) => `'${e.name}'`).join(', ')}] as const;`,
    'export type IconName = (typeof iconNames)[number];',
    '',
    'export const iconRegistry: Record<IconName, IconComponent> = {',
    ...entries.map((e) => `  '${e.name}': ${e.component},`),
    '};',
    '',
    'export const iconMeta: Record<IconName, { size: number; directional: boolean }> = {',
    ...entries.map((e) => `  '${e.name}': { size: ${e.size}, directional: ${e.directional} },`),
    '};',
    '',
    `export { ${entries.map((e) => e.component).join(', ')} };`,
    '',
  ].join('\n');
  fs.writeFileSync(path.join(outDir, 'index.ts'), index);
  return { outDir, count: entries.length };
}

function parseArgs(argv) {
  const out = {};
  for (let i = 0; i < argv.length; i++) {
    if (argv[i] === '--input') out.inputDir = argv[++i];
    else if (argv[i] === '--out-dir') out.outDir = argv[++i];
  }
  return out;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  try {
    const { count, outDir } = buildIcons(parseArgs(process.argv.slice(2)));
    console.log(`Generated ${count} icon components in ${outDir}`);
  } catch (err) {
    console.error(err.message);
    process.exit(1);
  }
}
